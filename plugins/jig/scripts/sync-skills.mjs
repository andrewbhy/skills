import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { statePath } from './jig-store.mjs';

function parseSkill(read, source, folder) {
  const text = read(source);
  const match = text.match(/^---\nname: ("[^\n]+")\ndescription: ("[^\n]+")\n---\n/);
  if (!match) throw new Error(`${source}: require JSON-quoted name and description frontmatter, in that order`);
  const name = JSON.parse(match[1]);
  const description = JSON.parse(match[2]);
  if (!/^jig-[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name) || name.length > 64 || name !== folder) {
    throw new Error(`${source}: name must be jig-<name>, lowercase with hyphens, matching its folder`);
  }
  if (typeof description !== 'string' || !description.trim() || description.length > 1024 || /[<>\r\n]/.test(description)) {
    throw new Error(`${source}: invalid description`);
  }
  const neutral = text.replace(/^## Provider notes\n[\s\S]*?(?=^## |$(?![\s\S]))/gm, '');
  // Fixed vocabulary is intentionally small; review still checks semantic differences.
  if (/\b(?:codex|claude|mcp|subagents?|spawn_agent)\b|\bTask tool\b|\/(?:code-review|review)(?![\w-])|\.claude\//i.test(neutral)) {
    throw new Error(`${source}: provider wording outside Provider notes`);
  }
  return { text, match, name };
}

// Optional packs (packs/<pack>/skills/<skill>/) are linked only when the project's
// .jig/config.json lists the pack in "packs"; core projects never see them.
function enabledPacks(root, read) {
  const path = statePath(root, 'config.json');
  if (!existsSync(path)) return [];
  const packs = JSON.parse(read(path)).packs ?? [];
  if (!Array.isArray(packs) || packs.some((pack) => typeof pack !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(pack))) {
    throw new Error('.jig/config.json: packs must be an array of lowercase pack names');
  }
  return packs;
}

// Deliberately support only two JSON-quoted YAML scalars, not a YAML parser.
// Both providers receive the same metadata; only the body is a pointer.
export function syncSkills(root, check = false) {
  const read = (path) => readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  const version = read(join(root, 'VERSION')).trim();
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('VERSION must be x.y.z');
  const sourceRoot = join(root, '.agents/skills');
  const targetRoot = join(root, '.claude/skills');
  const sources = readdirSync(sourceRoot, { withFileTypes: true });
  const expected = new Map();
  const supporting = new Map();
  const marker = read(join(root, 'scripts/telemetry-marker.mjs'));
  const store = read(join(root, 'scripts/jig-store.mjs'));
  for (const entry of sources) {
    if (!entry.isDirectory()) throw new Error(`Unexpected source entry: ${entry.name}`);
    const source = join(sourceRoot, entry.name, 'SKILL.md');
    const { text, match, name } = parseSkill(read, source, entry.name);
    expected.set(entry.name, `${match[0]}\n<!-- Generated by scripts/sync-skills.mjs; jig ${version}. Do not edit. -->\n\nRead [the canonical skill](../../../.agents/skills/${entry.name}/SKILL.md) and follow it. Resolve supporting files relative to that source, not this pointer.\n`);
    supporting.set(join(sourceRoot, entry.name, 'VERSION'), version + '\n');
    supporting.set(join(sourceRoot, entry.name, 'telemetry.mjs'), marker);
    supporting.set(join(sourceRoot, entry.name, 'jig-store.mjs'), store); // every helper resolves personal state through it
    if (['jig-correct', 'jig-review', 'jig-plan', 'jig-verify', 'jig-orchestrate'].includes(name)) {
      supporting.set(join(sourceRoot, name, 'signals.mjs'), read(join(root, 'scripts/signals.mjs')));
      supporting.set(join(sourceRoot, name, 'signal-kinds.md'), read(join(root, 'docs/signal-kinds.md')));
    }
    if (name === 'jig-orchestrate') {
      for (const script of ['queue', 'jobcheck', 'resource-guard']) supporting.set(join(sourceRoot, name, script + '.mjs'), read(join(root, 'scripts', script + '.mjs')));
      supporting.set(join(sourceRoot, name, 'queue.md'), read(join(root, 'docs/queue.md')));
      supporting.set(join(sourceRoot, name, 'scenarios.md'), read(join(root, 'docs/orchestrate-scenarios.md')));
    }
    if (name === 'jig-interaction') {
      supporting.set(join(sourceRoot, name, 'interaction-check.mjs'), read(join(root, 'scripts/interaction-check.mjs')));
      supporting.set(join(sourceRoot, name, 'interaction-feedback.mjs'), read(join(root, 'scripts/interaction-feedback.mjs')));
      supporting.set(join(sourceRoot, name, 'example.interaction.json'), read(join(root, 'tests/fixtures/interaction/clean.json')));
    }
    if (name === 'jig-mockup') {
      // The checker and the quality contract have one source each; the skill ships generated copies.
      supporting.set(join(sourceRoot, name, 'scripts/mockup-check.mjs'), read(join(root, 'scripts/mockup-check.mjs')));
      supporting.set(join(sourceRoot, name, 'IMPECCABLE-LICENSE.txt'), read(join(root, 'docs/design-toolbox/IMPECCABLE-LICENSE.txt')));
      const toolbox = read(join(root, 'docs/design-toolbox/README.md'));
      const foundations = toolbox.match(/^## Look foundations\n[\s\S]*?(?=^## |$(?![\s\S]))/m)?.[0];
      if (!foundations) throw new Error('Toolbox must define Look foundations');
      const components = toolbox.match(/^## Components and their quality bar\n[\s\S]*?(?=^## |$(?![\s\S]))/m)?.[0];
      const craft = toolbox.match(/^\| Check \| Rule \| Source \|\n[\s\S]*?(?=^\s*$|$(?![\s\S]))/m)?.[0];
      const motion = toolbox.match(/^## Motion basics\n[\s\S]*?(?=^## |$(?![\s\S]))/m)?.[0]
        ?.replaceAll('](motion-vocabulary.md)', '](../../../docs/design-toolbox/motion-vocabulary.md)')
        .replaceAll('](motion-recipes.md)', '](../../../docs/design-toolbox/motion-recipes.md)');
      const attribution = toolbox.match(/^## Borrowed practices and attribution\n[\s\S]*?(?=^## |$(?![\s\S]))/m)?.[0]
        ?.replace(/\]\((design-brief\.md|feedback-vocabulary\.md|design-inspector\.md)\)/g,
          '](../../../docs/design-toolbox/$1)');
      const states = toolbox.match(/^## Visual state contract\n[\s\S]*?(?=^## |$(?![\s\S]))/m)?.[0];
      if (!components || !craft || !motion || !attribution) throw new Error('Toolbox must define the component checklist, Craft basics, Motion basics and attribution');
      if (!states) throw new Error('Toolbox must define the visual state contract');
      supporting.set(join(sourceRoot, name, 'toolbox.md'), `# Mockup quality contract\n\n<!-- Generated from docs/design-toolbox/README.md by scripts/sync-skills.mjs. Do not edit. -->\n\n${foundations.trim()}\n\n${components.trim()}\n\n## Craft basics\n\n${craft.trim()}\n\n${motion.trim()}\n\n${states.trim()}\n\n${attribution.trim()}\n`);
    }
    if (text.includes('missed-problems.mjs') || text.includes('test-budget.mjs')) {
      supporting.set(join(sourceRoot, name, 'missed-problems.mjs'), read(join(root, 'scripts/missed-problems.mjs')));
      supporting.set(join(sourceRoot, name, 'missed-problems.md'), read(join(root, 'docs/missed-problems.md')).replaceAll('](test-budget.md#', '](testing.md#'));
      supporting.set(join(sourceRoot, name, 'testing.md'), read(join(root, 'docs/test-budget.md')));
    }
    if (text.includes('mockup-present.mjs')) {
      supporting.set(join(sourceRoot, name, 'scripts/mockup-present.mjs'), read(join(root, 'scripts/mockup-present.mjs')));
    }
    if (name === 'jig-review') {
      supporting.set(join(sourceRoot, entry.name, 'diff-signals.mjs'), read(join(root, 'scripts/diff-signals.mjs')));
    }
    if (name === 'jig-plan' || text.includes('[plan mode](plan-mode.md)')) {
      supporting.set(join(sourceRoot, name, 'plan-seats.mjs'), read(join(root, 'scripts/plan-seats.mjs')));
      supporting.set(join(sourceRoot, name, 'plan-mode.md'), read(join(root, 'docs/plan-mode.md')));
      supporting.set(join(sourceRoot, name, 'measures.md'), read(join(root, 'docs/measures.md')));
    }
    if (name === 'jig-plan') {
      for (const script of ['brief-check', 'openspec-plan']) supporting.set(join(sourceRoot, name, `${script}.mjs`), read(join(root, `scripts/${script}.mjs`)));
      for (const doc of ['plan-format.md', 'plan-sections.json']) supporting.set(join(sourceRoot, name, doc), read(join(root, `docs/${doc}`)));
      supporting.set(join(sourceRoot, name, 'NOTICE'), read(join(root, 'docs/licenses/OPENSPEC-MIT.txt')));
    }
    if (['jig-plan', 'jig-correct'].includes(name)) {
      supporting.set(join(sourceRoot, name, 'goal-translate.mjs'), read(join(root, 'scripts/goal-translate.mjs')));
      for (const doc of ['glossary.md', 'glossary.example.md', 'measures.md']) {
        supporting.set(join(sourceRoot, name, doc), read(join(root, `docs/${doc}`)));
      }
    }
    if (['jig-worktree', 'jig-merge'].includes(name)) {
      supporting.set(join(sourceRoot, entry.name, 'worktree.mjs'), read(join(root, 'scripts/worktree.mjs')));
      supporting.set(join(sourceRoot, entry.name, 'worktrees.md'), read(join(root, 'docs/worktrees.md')));
    }
    // Ship only with skills that use it; drafts activate this on coordinator installation.
    if (text.includes('test-budget.mjs')) {
      supporting.set(join(sourceRoot, entry.name, 'test-budget.mjs'), read(join(root, 'scripts/test-budget.mjs')));
      supporting.set(join(sourceRoot, entry.name, 'testing.md'), read(join(root, 'docs/test-budget.md')));
    }
    if (name === 'jig-verify' && text.includes('visual-check.mjs')) {
      for (const script of ['resource-guard', 'visual-clip', 'visual-reflow', 'visual-motion', 'visual-spacing', 'visual-components', 'visual-pixels', 'visual-visibility', 'visual-check', 'visual-alignment', 'visual-overlap', 'visual-crisp', 'style-lint', 'ui-tokens-check', 'visual-static', 'visual-ink', 'visual-layered', 'visual-changes', 'visual-state-snapshot', 'impeccable-inspector', 'design-inspector']) {
        supporting.set(join(sourceRoot, name, `${script}.mjs`), read(join(root, `scripts/${script}.mjs`)));
      }
      supporting.set(join(sourceRoot, name, 'visual-checks.md'), read(join(root, 'docs/visual-checks.md')));
      supporting.set(join(sourceRoot, name, 'impeccable-pin.json'), read(join(root, 'scripts/impeccable-pin.json')));
      supporting.set(join(sourceRoot, name, 'IMPECCABLE-LICENSE.txt'), read(join(root, 'docs/design-toolbox/IMPECCABLE-LICENSE.txt')));
      const { dependencies } = JSON.parse(read(join(root, 'package.json')));
      supporting.set(join(sourceRoot, name, 'package.json'), JSON.stringify({ private: true, dependencies: { 'playwright-core': dependencies['playwright-core'] } }, null, 2) + '\n');
    }
  }
  for (const pack of enabledPacks(root, read)) {
    const packSkills = join(root, 'packs', pack, 'skills');
    if (!existsSync(packSkills)) throw new Error(`Unknown pack: ${pack}`);
    for (const entry of readdirSync(packSkills, { withFileTypes: true })) {
      if (!entry.isDirectory()) throw new Error(`Unexpected pack entry: ${pack}/${entry.name}`);
      if (expected.has(entry.name)) throw new Error(`Pack skill ${entry.name} collides with another skill`);
      const { match } = parseSkill(read, join(packSkills, entry.name, 'SKILL.md'), entry.name);
      expected.set(entry.name, `${match[0]}\n<!-- Generated by scripts/sync-skills.mjs; jig ${version}. Do not edit. -->\n\nRead [the canonical skill](../../../packs/${pack}/skills/${entry.name}/SKILL.md) and follow it. Resolve supporting files relative to that source, not this pointer.\n`);
      supporting.set(join(packSkills, entry.name, 'VERSION'), version + '\n');
    }
  }
  if (existsSync(targetRoot)) {
    for (const entry of readdirSync(targetRoot)) {
      if (!expected.has(entry)) throw new Error(`Orphan pointer: ${entry}; remove it explicitly`);
    }
  }
  // Validate all sources before writing any pointers.
  for (const [folder, content] of expected) {
    const target = join(targetRoot, folder, 'SKILL.md');
    if (check) {
      if (!existsSync(target) || read(target) !== content) throw new Error(`Pointer drift: ${target}; run node scripts/sync-skills.mjs`);
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
  for (const [target, content] of supporting) {
    if (check) {
      if (!existsSync(target) || read(target) !== content) throw new Error(`Supporting file drift: ${target}; run node scripts/sync-skills.mjs`);
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
  return expected.size;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    if (process.argv.slice(2).some((arg) => arg !== '--check') || process.argv.length > 3) {
      throw new Error('Usage: node scripts/sync-skills.mjs [--check]');
    }
    const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
    const count = syncSkills(root, process.argv.includes('--check'));
    console.log(`${count} skill pointer(s) ${process.argv.includes('--check') ? 'checked' : 'generated'}.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
