import { commandFor as __jigCommandFor, isEntry as __jigIsEntry } from "../../../scripts/command-line.mjs";
if (process.argv[2] === '--help' && __jigIsEntry(import.meta.url)) { console.log('Usage: ' + __jigCommandFor(import.meta.url) + ' <arguments>; see the owning skill for commands.'); process.exit(0); }
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { packNames, paletteTokens, harmonyFor, sourceFor, presentationFor } from './palette.mjs';

const directory = path.dirname(fileURLToPath(import.meta.url));
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error(`Usage: ${__jigCommandFor(import.meta.url)} [--check]`);
for (const name of packNames) {
  const folder = path.join(directory, name);
  const source = sourceFor(name);
  const manifest = { name, mode: source.mode, author: name === 'dracula' ? 'jig contributors; Dracula Theme, created by Zeno Rocha' : 'jig contributors',
    licence: name === 'dracula' ? 'MIT (Dracula palette); UNLICENSED (jig additions)' : 'UNLICENSED', version: '0.6.0',
    description: name.startsWith('white-board') ? `White canvas and light chrome; ${name.endsWith('soft') ? 'tinted cards with coloured edges' : 'solid coloured type headers'}.` : source.adaptation ?? 'Dracula palette adapted to complete semantic roles; neutral reading text and accessible state fills.',
    source: { id: source.id, group: source.name, scheme: source.scheme, file: `gallery/${name === 'dracula' ? 'palettes' : 'contrast-palettes'}.mjs`,
      ...(name === 'dracula' ? { attribution: 'Dracula Theme; created by Zeno Rocha', licence: 'MIT', licenceFile: 'LICENSE-Dracula.txt', revision: '8d33e5492b56740c4857c5ebe7c5d5ab4040caf1',
        url: 'https://github.com/dracula/dracula-theme/blob/8d33e5492b56740c4857c5ebe7c5d5ab4040caf1/README.md' } : {}) },
    presentation: presentationFor(name), harmony: harmonyFor(name) };
  const css = await readFile(path.join(folder, 'theme.css'), 'utf8').catch(error => { if (error.code === 'ENOENT' && !process.argv.includes('--check')) return ''; throw error; });
  const values = paletteTokens(name, manifest.mode);
  // Share the established geometry, typography and motion without modifying the archive.
  const base = await readFile(path.join(directory, 'retired/calm-workbench/theme.css'), 'utf8');
  const rest = base.slice(base.indexOf('  --stroke-accent:'))
    .replace(/--font-interface:[^;]+;/, '--font-interface: var(--jig-font-sans);')
    .replace(/--font-code:[^;]+;/, '--font-code: var(--jig-font-mono);')
    .replace(/--text-meta:[^;]+;/, '--text-meta: var(--type-sm);')
    .replace(/--text-body:[^;]+;/, '--text-body: var(--type-body);')
    .replace(/--text-label:[^;]+;/, '--text-label: var(--type-body);')
    .replace(/--text-section:[^;]+;/, '--text-section: var(--type-section);')
    .replace(/--text-pane-title:[^;]+;/, '--text-pane-title: var(--type-title);')
    .replace(/--text-app-title:[^;]+;/, '--text-app-title: var(--type-title);')
    .replace(/--leading-meta:[^;]+;/, '--leading-meta: var(--line-sm);')
    .replace(/--leading-body:[^;]+;/, '--leading-body: var(--line-body);')
    .replace(/--leading-heading:[^;]+;/, '--leading-heading: var(--line-title);')
    .replace(/--leading-code:[^;]+;/, '--leading-code: var(--line-body);')
    .replace(/--weight-body:[^;]+;/, '--weight-body: var(--weight-regular);')
    .replace(/--weight-emphasis:[^;]+;/, '--weight-emphasis: var(--weight-strong);')
    .replace(/--tracking-interface:[^;]+;/, '--tracking-interface: var(--track-body);');
  const result = `/* Pass 7 palette adaptation. Source and licence: theme.json. Generated by ../build-palettes.mjs. */\n@import url("../../typography/type.css");\n:root {\n  color-scheme: ${manifest.mode};\n` +
    Object.entries(values).map(([key, value]) => `  --${key}: ${value};`).join('\n') +
    `\n  --overlay-scrim: ${manifest.mode === 'dark' ? '#080a0cbb' : '#15223588'};\n` + rest.replace(/\r\n/g, '\n');
  if (process.argv.includes('--check')) {
    if (css !== result) throw new Error(`${name}: generated palette drift; run build-palettes.mjs`);
    if (await readFile(path.join(folder, 'theme.json'), 'utf8') !== JSON.stringify(manifest, null, 2) + '\n') throw new Error(`${name}: generated manifest drift; run build-palettes.mjs`);
  } else {
    await mkdir(folder, { recursive: true });
    await writeFile(path.join(folder, 'theme.css'), result);
    await writeFile(path.join(folder, 'theme.json'), JSON.stringify(manifest, null, 2) + '\n');
  }
  if (name === 'dracula') {
    const notice = (await readFile(path.join(directory, 'gallery/licences/dracula.txt'), 'utf8')).replace(/\r\n/g, '\n');
    const noticePath = path.join(folder, 'LICENSE-Dracula.txt');
    if (process.argv.includes('--check')) {
      if (await readFile(noticePath, 'utf8') !== notice) throw new Error('Dracula licence drift; run build-palettes.mjs');
    } else await writeFile(noticePath, notice);
  }
}
// Embed the same harmony metadata for file:// previews without fetching JSON.
const previewPath = path.join(directory, 'preview.html');
const preview = await readFile(previewPath, 'utf8');
const data = JSON.stringify(Object.fromEntries(packNames.map(name => [name, harmonyFor(name)])), null, 2);
const previewResult = preview.replace(/<!-- harmony:start -->[\s\S]*?<!-- harmony:end -->/, `<!-- harmony:start -->\n<script id="harmony-data" type="application/json">\n${data}\n</script>\n<!-- harmony:end -->`);
if (previewResult === preview && !preview.includes(data)) throw new Error('Missing preview harmony markers');
if (process.argv.includes('--check')) {
  if (preview !== previewResult) throw new Error('Preview harmony drift; run build-palettes.mjs');
} else await writeFile(previewPath, previewResult);
console.log(`${packNames.length} palette blocks ` + (process.argv.includes('--check') ? 'match.' : 'written.'));
